"""Credential handling for git subprocesses.

The rule this module exists to enforce: **a GitHub token never appears in
argv**. argv is world-readable through the process table on Linux (``ps -ef``)
and through WMI on Windows, and it is echoed verbatim into every error message
we surface. So the token is passed through the environment and read back by a
tiny askpass helper, which is the only supported git mechanism for this.

``GIT_TERMINAL_PROMPT=0`` is the belt to that braces: if the askpass helper is
ever missing or fails, git errors out immediately instead of blocking forever
on a prompt that has no terminal to answer it.
"""

from __future__ import annotations

import contextlib
import os
import stat
import tempfile
from pathlib import Path

#: Environment variable git's askpass helper reads the secret from.
PASSWORD_ENV = "CODEPILOTAI_GIT_PASSWORD"

#: Posix helper. Echoing an env var cannot leak it via a process listing,
#: because the child never puts the value into its own argv.
_ASKPASS_SH = """#!/bin/sh
# Generated by CodePilotAI. Prints the credential git asked for.
case "$1" in
    *sername*) printf 'x-access-token\\n' ;;
    *)        printf '%s\\n' "$CODEPILOTAI_GIT_PASSWORD" ;;
esac
"""

#: Windows helper. A .cmd file is executable by CreateProcess via git's
#: run_command shim, which is the portable option here; Git for Windows does
#: not run a bare .sh through GIT_ASKPASS.
_ASKPASS_CMD = """@echo off
setlocal
set "prompt=%~1"
echo %prompt% | findstr /C:"ername" >nul && (echo x-access-token & exit /b 0)
<nul set /p="%CODEPILOTAI_GIT_PASSWORD%"
echo.
"""


class AskpassHelper:
    """A generated askpass script plus the environment that feeds it.

    Use as a context manager so the script is deleted and its mode reset even
    if the git call raises::

        with askpass_helper(workspace) as helper:
            run_git(["fetch"], cwd=mirror, env_extra=helper.env())
    """

    __slots__ = ("_directory", "_env", "path")

    def __init__(self, directory: Path) -> None:
        self._directory = directory
        directory.mkdir(parents=True, exist_ok=True)
        suffix = ".cmd" if os.name == "nt" else ".sh"
        self.path = directory / f"askpass{suffix}"
        self.path.write_text(_ASKPASS_CMD if os.name == "nt" else _ASKPASS_SH, encoding="utf-8")
        if os.name != "nt":
            # Owner-only: the script is harmless, but the directory next to it
            # holds a token in its environment and we do not want a wider net.
            self.path.chmod(self.path.stat().st_mode | stat.S_IXUSR)

    def env(self, secret: str) -> dict[str, str]:
        """Return the env additions that expose ``secret`` to the helper."""
        return {
            "GIT_ASKPASS": str(self.path),
            "GIT_TERMINAL_PROMPT": "0",
            PASSWORD_ENV: secret,
        }

    def __enter__(self) -> AskpassHelper:
        return self

    def __exit__(self, *_: object) -> None:
        self.destroy()

    def destroy(self) -> None:
        """Remove the script. A leftover file is hygiene, never a task failure."""
        with contextlib.suppress(OSError):
            self.path.unlink(missing_ok=True)


def askpass_helper_in(directory: Path) -> AskpassHelper:
    """Build an askpass helper inside an existing directory."""
    return AskpassHelper(directory)


def scratch_dir(parent: Path, prefix: str = "run-") -> tempfile.TemporaryDirectory[str]:
    """Create a throwaway directory used as HOME for a git invocation.

    Pointing ``HOME`` at a scratch directory stops git from reading the
    operator's global config, which may contain ``insteadOf`` rewrites, hooks,
    or credential helpers that would silently redirect our pushes.
    """
    return tempfile.TemporaryDirectory(prefix=prefix, dir=str(parent))
