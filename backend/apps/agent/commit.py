"""Commit phase: one clean conventional commit from the approved changes.

The message is generated by the model at low reasoning effort (writing a
subject and body is mechanical), then normalised so it always starts with a
conventional-commit prefix (Task.md §1 step 7 / §5). If the model call yields
nothing usable -- an empty completion is the failure mode a bounded prompt can
hit -- a deterministic subject is derived from the agent's summary instead, so
commit never fails a run that already did the work.

The commit itself is staged through :func:`apps.git.worktree.stage_all`, which
excludes the agent's scratch ``.codepilotai-home`` directory, and created with
``--no-verify``: the repo's own checks were already run by the verify phase,
and re-running them here would duplicate cost without new information.
"""

from __future__ import annotations

import re
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

from langchain_core.messages import BaseMessage, HumanMessage, SystemMessage

from apps.agent.budget import Budget
from apps.agent.graph import ExecOutcome, build_agent_graph, initial_state
from apps.agent.providers.base import Provider, ToolCall
from apps.agent.tools import ToolResult
from apps.git.worktree import commit, stage_all
from config.observability import get_logger

logger = get_logger(__name__)

__all__: list[str] = [
    "CONVENTIONAL_PREFIXES",
    "CommitResult",
    "deterministic_subject",
    "run_commit_phase",
]

#: Conventional-commit prefixes the message may start with (Task.md §5).
CONVENTIONAL_PREFIXES = frozenset(
    {"feat", "fix", "refactor", "chore", "docs", "test", "perf", "build", "ci", "revert"}
)

_MAX_SUBJECT_CHARS = 72


@dataclass(frozen=True, slots=True)
class CommitResult:
    """The commit phase outcome."""

    message: str
    #: HEAD sha after the commit, or ``None`` when there was nothing to commit.
    sha: str | None
    staged: tuple[str, ...]
    fallback: bool


def run_commit_phase(
    *,
    provider: Provider,
    system: SystemMessage,
    prompt: HumanMessage,
    worktree: Path,
    budget: Budget,
    reasoning_effort: str = "low",
    fallback_message: str,
) -> CommitResult:
    """Generate a conventional message, stage the change, and commit.

    ``fallback_message`` is used when the model yields no usable message.
    Returns a :class:`CommitResult` whose ``sha`` is ``None`` if nothing was
    staged (e.g. every change was rejected or already committed).
    """
    message = _suggest_message(provider, system, prompt, budget, reasoning_effort)
    fallback = False
    if not message:
        message = fallback_message
        fallback = True
    message = conventionalise(message)

    staged = stage_all(worktree)
    if not staged:
        logger.info("commit_skipped_nothing_staged")
        return CommitResult(message=message, sha=None, staged=(), fallback=fallback)

    sha = commit(worktree, message=message)
    logger.info("commit_created", sha=sha, files=staged)
    return CommitResult(message=message, sha=sha, staged=tuple(staged), fallback=fallback)


def conventionalise(message: str) -> str:
    """Normalise a model message into a conventional commit.

    Keeps the model's wording but guarantees the ``type:`` prefix, caps the
    subject at 72 characters, and bounds the whole message so a runaway
    completion cannot swamp the task row.
    """
    text = message.strip().strip('"').strip("'")
    if not text:
        return text

    first_line = text.splitlines()[0]
    prefix = first_line.split(":", 1)[0].lower()
    if prefix not in CONVENTIONAL_PREFIXES:
        text = f"chore: {text}"

    lines = text.splitlines()
    subject = lines[0]
    if len(subject) > _MAX_SUBJECT_CHARS:
        lines[0] = subject[: _MAX_SUBJECT_CHARS - 1].rstrip() + "…"
    body = "\n".join(lines[1:])
    if len(body) > 4000:
        body = body[:3997] + "…"
    return "\n".join([lines[0], body]).strip("\n")


def deterministic_subject(change_types: Sequence[str], summary: str) -> str:
    """A predictable conventional subject when the model call produces nothing.

    ``summary`` is the agent's reviewer-facing finish summary, already present
    as ``AgentTask.agent_summary`` by the time commit runs.
    """
    types = set(change_types)
    lowered = (summary or "").lower()
    if "fix" in lowered or "bug" in lowered or "error" in lowered:
        prefix = "fix"
    elif "refactor" in lowered or "clean" in lowered:
        prefix = "refactor"
    elif "remove" in lowered or "delete" in lowered:
        prefix = "chore"
    elif types & {"create"}:
        prefix = "feat"
    else:
        prefix = "chore"

    base = re.sub(r"\s+", " ", summary or "apply agent changes").strip()
    if not base:
        base = "apply agent changes"
    first_sentence = base.split(".", 1)[0][: _MAX_SUBJECT_CHARS - len(prefix) - 2].rstrip()
    if not first_sentence:
        first_sentence = "apply agent changes"
    return f"{prefix}: {first_sentence}"


# ── internals ─────────────────────────────────────────────────────────────────


def _suggest_message(
    provider: Provider,
    system: SystemMessage,
    task: HumanMessage,
    budget: Budget,
    reasoning_effort: str,
) -> str:
    """Ask the model for the message via the shared loop with no tools."""

    def executor(call: ToolCall) -> ExecOutcome:
        # The commit phase exposes no tools; a tool call here is a protocol bug.
        return ExecOutcome(
            result=ToolResult(
                name=call.name,
                content="No tools are available in the commit phase.",
                is_error=True,
            )
        )

    graph = build_agent_graph(
        provider=provider,
        tool_schemas=[],
        executor=executor,
        budget=budget,
        reasoning_effort=reasoning_effort,
        max_tool_calls=1,
    )
    final = graph.invoke(
        initial_state(system=system, task=task, max_tool_calls=1),
        config={"recursion_limit": 4},
    )
    return _last_assistant_text(final.get("messages", []))


def _last_assistant_text(messages: list[BaseMessage]) -> str:
    """The most recent non-empty assistant turn, or ``""``."""
    from langchain_core.messages import AIMessage

    for message in reversed(messages):
        if isinstance(message, AIMessage) and message.content and not message.tool_calls:
            return str(message.content).strip()
    return ""
